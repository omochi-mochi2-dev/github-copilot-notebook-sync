"""パス判定・フラットタブ命名ユーティリティ（docs/Detailed_Logic.md §2, §3 準拠）。

github_client / docs_client / main の双方から利用されるため、循環 import を避ける目的で
独立モジュールとして配置する。
"""

from __future__ import annotations

import hashlib
import posixpath
from collections.abc import Iterable

from src.models import (
    MAX_TAB_TITLE_LENGTH,
    TAB_TITLE_HASH_LENGTH,
    TAB_TITLE_PREFIX_LENGTH,
)


def normalize_path(path: str) -> str:
    """区切り文字を `/` に統一し、前後の `/` を除去する。"""
    return path.replace("\\", "/").strip("/")


def is_valid_sync_file(filename: str) -> bool:
    """
    同期対象とする Markdown ファイルかを判定する。
    - 拡張子が .md または .txt であること。
    - ナビゲーション用の index.md は完全除外する。
    """
    # 1. 拡張子チェック
    if not (filename.endswith(".md") or filename.endswith(".txt")):
        return False

    # 2. index.md の完全除外（末尾一致またはパス境界一致）
    if filename == "index.md" or filename.endswith("/index.md") or filename.endswith("\\index.md"):
        return False

    return True


def is_under_watch_folder(file_path: str, watch_folder: str) -> bool:
    """file_path が watch_folder 配下（パス境界一致）にあるかを判定する。"""
    normalized_path = normalize_path(file_path)
    normalized_folder = normalize_path(watch_folder)
    return normalized_path.startswith(normalized_folder + "/")


def find_watch_folder(file_path: str, watch_folders: Iterable[str]) -> str | None:
    """file_path を含む監視フォルダのうち、最も深い（長い）ものを返す。"""
    matches = [wf for wf in watch_folders if is_under_watch_folder(file_path, wf)]
    if not matches:
        return None
    return max(matches, key=lambda wf: len(normalize_path(wf)))


def relative_path_from_watch_parent(file_path: str, watch_folder: str) -> str:
    """
    監視フォルダの「親」からの相対パスを返す（監視フォルダ名自体を含む）。
    例: ('content/copilot/concepts/foo.md', 'content/copilot/concepts') -> 'concepts/foo.md'
    """
    normalized_path = normalize_path(file_path)
    normalized_folder = normalize_path(watch_folder)
    if not is_under_watch_folder(normalized_path, normalized_folder):
        raise ValueError(f"'{file_path}' is not under watch folder '{watch_folder}'")
    parent = posixpath.dirname(normalized_folder)
    if not parent:
        return normalized_path
    return normalized_path[len(parent) + 1 :]


def generate_flat_tab_title(relative_path: str) -> str:
    """
    相対パスから Google Docs タブ名を一意かつ安全に生成する（最大50文字）。
    例: 'concepts/agent-capabilities/about-agents.md'
        -> 'concepts_agent-capabilities_about-agents_md' (43文字)
    """
    flat = relative_path.replace("/", "_").replace("\\", "_").replace(".", "_")

    if len(flat) <= MAX_TAB_TITLE_LENGTH:
        return flat

    hash_digest = hashlib.sha256(flat.encode("utf-8")).hexdigest()[:TAB_TITLE_HASH_LENGTH]
    return f"{flat[:TAB_TITLE_PREFIX_LENGTH]}_{hash_digest}"


def tab_title_for_path(file_path: str, watch_folders: Iterable[str]) -> str | None:
    """ファイルパスから最終的なタブ名を生成する。監視対象外なら None。"""
    folder = find_watch_folder(file_path, watch_folders)
    if folder is None:
        return None
    return generate_flat_tab_title(relative_path_from_watch_parent(file_path, folder))


def validate_unique_titles(path_to_title: dict[str, str]) -> None:
    """同一ドキュメント内でタブ名が衝突していないかを検証する。衝突時は RuntimeError。"""
    seen: dict[str, str] = {}
    for path, title in path_to_title.items():
        if title in seen and seen[title] != path:
            raise RuntimeError(
                f"Tab title collision detected: '{title}' is generated by both "
                f"'{seen[title]}' and '{path}'. Aborting."
            )
        seen[title] = path

